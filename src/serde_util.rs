use serde::{Deserialize, Deserializer};

/// Deserialize a `null` into the default value of the type.
///
/// The Casdoor server is written in Go, where an empty slice or map is marshalled as
/// `null` instead of as `[]` or `{}`, so every collection field of the SDK structs is
/// deserialized through this function.
pub(crate) fn null_to_default<'de, D, T>(deserializer: D) -> Result<T, D::Error>
where
    D: Deserializer<'de>,
    T: Default + Deserialize<'de>,
{
    Ok(Option::<T>::deserialize(deserializer)?.unwrap_or_default())
}
